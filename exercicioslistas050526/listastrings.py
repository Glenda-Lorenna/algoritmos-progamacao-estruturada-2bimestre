# Criando uma lista com 5 nomes

nomes = ["Maria", "Joana", "Rita", "João", "Simão"]

# Exibindo todos os nomes da lista
print("Lista de nomes:", nomes)

# Exibindo o primeiro nome da lista
print("Primeiro nome:", nomes[0])

# Exibindo o último nome da lista
print("Último nome:", nomes[-1])

# Quantidade de nomes na lista
print("Quantidade de nomes:", len(nomes))